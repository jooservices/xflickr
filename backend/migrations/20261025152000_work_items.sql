CREATE TABLE IF NOT EXISTS work_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind TEXT NOT NULL,
    subject_key TEXT NOT NULL,
    user_id BIGINT REFERENCES users (id) ON DELETE CASCADE,
    key_id BIGINT REFERENCES api_keys (id) ON DELETE SET NULL,
    state TEXT NOT NULL DEFAULT 'pending',
    cursor JSONB NOT NULL DEFAULT '{}'::jsonb,
    priority_base INTEGER NOT NULL DEFAULT 0,
    attempts INTEGER NOT NULL DEFAULT 0,
    not_before TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    last_error TEXT,
    CONSTRAINT work_items_state_known CHECK (state IN ('pending', 'ready', 'running', 'waiting', 'done', 'failed')),
    CONSTRAINT work_items_attempts_nonnegative CHECK (attempts >= 0),
    CONSTRAINT work_items_dedupe_key UNIQUE NULLS NOT DISTINCT (kind, subject_key, user_id)
);

CREATE INDEX IF NOT EXISTS work_items_ready_idx ON work_items (priority_base DESC, not_before, id)
