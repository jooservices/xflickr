-- Public keys are stored in plaintext so workers can call Flickr. Responses
-- mask them. secret_sealed is an envelope from platform/crypto, bound to
-- associated data api_keys:<id>. The secret is never selected by the API.
CREATE TABLE api_keys (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    label TEXT NOT NULL,
    key_public TEXT NOT NULL,
    secret_sealed JSONB NOT NULL,
    per_hour_limit INTEGER NOT NULL,
    per_second_limit INTEGER NOT NULL,
    burst INTEGER NOT NULL,
    status TEXT NOT NULL DEFAULT 'valid',
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT api_keys_label_len CHECK (char_length(label) BETWEEN 1 AND 80),
    CONSTRAINT api_keys_public_len CHECK (char_length(key_public) BETWEEN 1 AND 255),
    CONSTRAINT api_keys_per_hour_limit_positive CHECK (per_hour_limit > 0),
    CONSTRAINT api_keys_per_second_limit_positive CHECK (per_second_limit > 0),
    CONSTRAINT api_keys_burst_positive CHECK (burst > 0),
    CONSTRAINT api_keys_status_known CHECK (status IN ('valid', 'invalid', 'revoked')),
    CONSTRAINT api_keys_user_public_unique UNIQUE (user_id, key_public)
);

CREATE INDEX api_keys_user_id_idx ON api_keys (user_id);

-- Connected accounts are marked reconnect_required when a key secret changes.
-- OAuth token columns are added by the account connection flow.
CREATE TABLE connected_accounts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    api_key_id BIGINT NOT NULL REFERENCES api_keys (id) ON DELETE CASCADE,
    status TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT connected_accounts_status_known CHECK (status IN ('connected', 'reconnect_required'))
);

CREATE INDEX connected_accounts_api_key_id_idx ON connected_accounts (api_key_id);

