-- +goose Up
-- Connected Flickr accounts replace the placeholder connected_accounts table
-- from the API key migration. No flow wrote to it, so no rows are carried over.
-- token_sealed and secret_sealed are envelopes from platform/crypto, bound to
-- associated data flickr_accounts:<id>:token and flickr_accounts:<id>:secret.
-- The token belongs to key_id: deleting the key deletes its accounts.
DROP TABLE connected_accounts;

CREATE TABLE flickr_accounts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    key_id BIGINT NOT NULL REFERENCES api_keys (id) ON DELETE CASCADE,
    nsid TEXT NOT NULL,
    username TEXT NOT NULL,
    token_sealed JSONB NOT NULL,
    secret_sealed JSONB NOT NULL,
    status TEXT NOT NULL DEFAULT 'ok',
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT flickr_accounts_nsid_len CHECK (char_length(nsid) BETWEEN 1 AND 255),
    CONSTRAINT flickr_accounts_status_known CHECK (status IN ('ok', 'reconnect_required', 'revoked')),
    CONSTRAINT flickr_accounts_user_nsid_unique UNIQUE (user_id, nsid)
);

CREATE INDEX flickr_accounts_key_id_idx ON flickr_accounts (key_id);

-- +goose Down
DROP TABLE flickr_accounts;

CREATE TABLE connected_accounts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    api_key_id BIGINT NOT NULL REFERENCES api_keys (id) ON DELETE CASCADE,
    status TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT connected_accounts_status_known CHECK (status IN ('connected', 'reconnect_required'))
);

CREATE INDEX connected_accounts_api_key_id_idx ON connected_accounts (api_key_id);
