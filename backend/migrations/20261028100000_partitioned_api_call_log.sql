-- +goose Up
-- api_call_log currently doubles as a short-lived quota recovery ledger. Keep
-- its legacy columns while moving it to daily partitions for richer call data.
-- Partition by called_at so legacy inserts that omit at can still be routed;
-- the row trigger fills at after PostgreSQL has selected the daily partition.
ALTER TABLE api_call_log RENAME TO api_call_log_legacy;

CREATE TABLE api_call_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY (SEQUENCE NAME api_call_log_partition_id_seq),
    at TIMESTAMPTZ NOT NULL,
    key_id BIGINT NOT NULL REFERENCES api_keys (id) ON DELETE CASCADE,
    class TEXT,
    called_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    user_id BIGINT REFERENCES users (id) ON DELETE SET NULL,
    account_id BIGINT REFERENCES flickr_accounts (id) ON DELETE SET NULL,
    node TEXT,
    method TEXT,
    status TEXT,
    error_code BIGINT,
    latency_ms BIGINT CHECK (latency_ms IS NULL OR latency_ms >= 0),
    bytes BIGINT CHECK (bytes IS NULL OR bytes >= 0),
    lane TEXT,
    PRIMARY KEY (called_at, id)
) PARTITION BY RANGE (called_at);

-- +goose StatementBegin
CREATE OR REPLACE FUNCTION sync_api_call_log_at() RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    IF NEW.at IS NULL THEN
        NEW.at := COALESCE(NEW.called_at, now());
    END IF;
    IF NEW.called_at IS NULL THEN
        NEW.called_at := NEW.at;
    END IF;
    RETURN NEW;
END;
$$;
-- +goose StatementEnd

CREATE TRIGGER api_call_log_sync_at
BEFORE INSERT ON api_call_log
FOR EACH ROW EXECUTE FUNCTION sync_api_call_log_at();

CREATE INDEX api_call_log_key_at_idx ON api_call_log (key_id, at);
CREATE INDEX api_call_log_at_idx ON api_call_log (at);
CREATE INDEX api_call_log_method_at_idx ON api_call_log (method, at) WHERE method IS NOT NULL;

-- Create all partitions needed for the legacy rows, the retention window, and
-- the seven-day forward horizon before copying quota recovery history.
-- +goose StatementBegin
DO $$
DECLARE
    utc_today DATE := (now() AT TIME ZONE 'UTC')::date;
    first_day DATE;
    last_day DATE;
    partition_day DATE;
    lower_bound TIMESTAMPTZ;
    upper_bound TIMESTAMPTZ;
BEGIN
    SELECT min((called_at AT TIME ZONE 'UTC')::date), max((called_at AT TIME ZONE 'UTC')::date)
      INTO first_day, last_day
      FROM api_call_log_legacy;
    first_day := LEAST(COALESCE(first_day, utc_today - 30), utc_today - 30);
    last_day := GREATEST(COALESCE(last_day, utc_today), utc_today + 7);
    FOR partition_day IN SELECT generate_series(first_day, last_day, interval '1 day')::date LOOP
        lower_bound := partition_day::timestamp AT TIME ZONE 'UTC';
        upper_bound := (partition_day + 1)::timestamp AT TIME ZONE 'UTC';
        EXECUTE format(
            'CREATE TABLE %I PARTITION OF api_call_log FOR VALUES FROM (%L) TO (%L)',
            'api_call_log_' || to_char(partition_day, 'YYYYMMDD'), lower_bound, upper_bound
        );
    END LOOP;
END;
$$;
-- +goose StatementEnd

INSERT INTO api_call_log (id, at, key_id, class, called_at)
SELECT id, called_at, key_id, class, called_at
FROM api_call_log_legacy
ORDER BY called_at;

SELECT setval('api_call_log_partition_id_seq', COALESCE(max(id), 1), max(id) IS NOT NULL)
FROM api_call_log;

DROP TABLE api_call_log_legacy;

