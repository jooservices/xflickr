#!/usr/bin/env python3
"""Reconcile the HTTP paths the web calls with contracts/openapi and the generated Go router.

Writes docs/api-reconciliation.md and fails when the web
  - calls a path that is not in contracts/openapi or not routed by the backend, or
  - calls any path through hand-written fetch/request code instead of the generated client.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

# The fetch wrapper behind the generated client may name the session-refresh path itself.
TRANSPORT = {"shared/api/mutator.ts"}
HAND_WRITTEN_CALL = re.compile(
    r"\b(?:fetch|request|csrfFetch|fetchJson|sendRequest|EventSource)\s*(?:<[^>()]*>)?\(\s*(['\"`])(/[^'\"`]*)\1"
)
HAND_WRITTEN_API = re.compile(r"\b(?:request|fetchJson|sendRequest)\s*\(")


def route_key(path: str) -> str:
    return re.sub(r"\$\{[^}]+\}|\{[^}]+\}", "{}", path).split("?", 1)[0]


def is_test(relative: str) -> bool:
    return relative.startswith("test/") or ".test." in relative or relative.endswith(".spec.ts")


def generated_paths(directory: Path, prefixes: tuple[str, ...]) -> set[str]:
    paths = set()
    for file in directory.rglob("*.ts"):
        for match in re.finditer(r"(['`])(/[^'`\n]*)\1", file.read_text()):
            if match.group(2).startswith(prefixes):
                paths.add(route_key(match.group(2)))
    return paths


def collect(root: Path) -> tuple[set[str], set[str], set[str], list[str]]:
    contract_text = (root / "contracts/openapi/openapi.yaml").read_text()
    contract = set(re.findall(r"^  (\/[^:]+):", contract_text, re.MULTILINE))
    prefixes = tuple(sorted({"/" + path.split("/")[1] for path in contract}))

    router_text = (root / "backend/internal/platform/api/gen/server.gen.go").read_text()
    backend = set(re.findall(r'options\.BaseURL\s*\+\s*"(\/[^" ]+)"', router_text))

    web: set[str] = set()
    hand_written: list[str] = []
    src = root / "web/src"
    if src.exists():
        generated = src / "shared/api/gen"
        if generated.exists():
            web |= generated_paths(generated, prefixes)
        for file in sorted(src.rglob("*.ts*")):
            relative = file.relative_to(src).as_posix()
            if is_test(relative) or relative.startswith("shared/api/gen/") or relative in TRANSPORT:
                continue
            for match in HAND_WRITTEN_CALL.finditer(file.read_text()):
                path = route_key(match.group(2))
                web.add(path)
                hand_written.append(f"{relative}: {match.group(2)}")
    return contract, backend, web, hand_written


def served(path: str, candidates: set[str]) -> str | None:
    return next((candidate for candidate in sorted(candidates) if route_key(candidate) == path), None)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[2])
    args = parser.parse_args()
    contract, backend, web, hand_written = collect(args.root)

    lines = [
        "# Web API reconciliation",
        "",
        "Generated by `docker/scripts/api-usage-check.sh` (part of `make lint`). It lists every HTTP path",
        "the web calls (generated client and hand-written code) with the OpenAPI path and the Go route",
        "that serve it, or `MISSING`.",
        "",
        "| Web path | OpenAPI | Go router |",
        "| --- | --- | --- |",
    ]
    for path in sorted(web):
        lines.append(f"| `{path}` | `{served(path, contract) or 'MISSING'}` | `{served(path, backend) or 'MISSING'}` |")
    output = "\n".join(lines) + "\n"
    if args.root.resolve() == Path(__file__).resolve().parents[2]:
        (args.root / "docs/api-reconciliation.md").write_text(output)
    else:
        print(output, end="")

    failures = []
    missing_contract = sorted(path for path in web if served(path, contract) is None)
    if missing_contract:
        failures.append("Web calls paths missing from OpenAPI: " + ", ".join(missing_contract))
    missing_router = sorted(path for path in web if served(path, backend) is None)
    if missing_router:
        failures.append("Web paths missing from the Go router: " + ", ".join(missing_router))
    if hand_written:
        failures.append("Hand-written API calls (use the generated client): " + "; ".join(hand_written))
    for failure in failures:
        print(failure, file=sys.stderr)
    return 1 if failures else 0


if __name__ == "__main__":
    raise SystemExit(main())
